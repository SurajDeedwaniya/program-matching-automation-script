def generate_brochure_markdown_report():
    # ✅ Load mismatches
    with open(os.path.join(WORKDIR,"brochure_mismatch_report.json"), "r") as f:
        mismatches = json.load(f)

    # ✅ Group mismatches by sheet and program id
    grouped = defaultdict(lambda: defaultdict(list))
    for m in mismatches:
        grouped[m["sheet"]][m["id"]].append(m)

    # ✅ Markdown lines
    lines = ["# ❌ Brochure Mismatch Report\n"]
    for sheet, programs in grouped.items():
        lines.append(f"## 📄 Sheet: `{sheet}`\n")
        for pid, items in programs.items():
            lines.append(f"### 🔹 Program ID: `{pid}`\n")
            lines.append("| Field | Sheet Value | Brochure Value |")
            lines.append("|-------|-------------|----------------|")
            for item in items:
                field = item["field"]
                sv = str(item["sheet_value"]).replace("\n", " ").strip()
                jv = str(item["brochure_match_info"]).replace("\n", " ").strip()
                lines.append(f"| {field} | {sv} | {jv} |")
            lines.append("")

    # ✅ Save markdown
    with open(os.path.join(WORKDIR,"brochure_report.md"), "w") as f:
        f.write("\n".join(lines))
    print("✅ Markdown saved to `/content/brochure_report.md`")

    # ✅ Collect mismatch rows grouped by sheet
    mismatches_by_sheet = defaultdict(list)
    for sheet, programs in grouped.items():
        for pid, items in programs.items():
            for item in items:
                mismatches_by_sheet[sheet].append({
                    "Sheet": sheet,
                    "Program ID": pid,
                    "Field": item["field"],
                    "Sheet Value": str(item["sheet_value"]).replace("\n", " ").strip(),
                    "Brochure Value": str(item["brochure_match_info"]).replace("\n", " ").strip()
                })

    # ✅ Load matches
    try:
        with open(os.path.join(WORKDIR,"match_brochure.json"), "r") as f:
            matches = json.load(f)
    except FileNotFoundError:
        matches = []

    # ✅ Load summary
    try:
        with open(os.path.join(WORKDIR,"brochure_status_summary.json"), "r") as f:
            summary = json.load(f)
    except FileNotFoundError:
        summary = []

    # ✅ Save all to Excel
    with pd.ExcelWriter(os.path.join(WORKDIR,"brochure_report.xlsx")) as writer:
        # Summary Sheet
        if summary:
            pd.DataFrame(summary).to_excel(writer, sheet_name="Summary", index=False)

        # Matches Sheet
        if matches:
            pd.DataFrame(matches).to_excel(writer, sheet_name="Matches", index=False)

        # Mismatches per sheet
        for sheet, rows in mismatches_by_sheet.items():
            df = pd.DataFrame(rows)
            # df_with_header = pd.DataFrame([["Sheet Name:", sheet]], columns=["Sheet", "Program ID"])
            # df_final = pd.concat([df_with_header, df], ignore_index=True)
            sheet_name_safe = f"{sheet} Mismatches"[:31]  # Excel limit
            df.to_excel(writer, sheet_name=sheet_name_safe, index=False)

    print("✅ Excel saved to `/content/brochure_report.xlsx` with summary, matches, and mismatches by sheet.")

