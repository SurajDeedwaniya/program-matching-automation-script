def normalize_tool_name(name):
          """Normalize tool names: remove punctuation, normalize unicode, lowercase."""
          name = unicodedata.normalize('NFKD', name)
          name = re.sub(r'[^\w\s]', '', name)  # Remove punctuation
          return name.strip().lower()


